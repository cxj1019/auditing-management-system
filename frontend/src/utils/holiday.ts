/** 某日期的节假日信息（无则 undefined） */
export function holidayOf(date: string): HolidayInfo | undefined {
  return DATA[date]
}

/** 是否法定休息日（普通周末不算） */
export function isHoliday(date: string): boolean {
  return DATA[date]?.type === '休'
}

/** 是否调休上班日 */
export function isMakeupWorkday(date: string): boolean {
  return DATA[date]?.type === '班'
}
